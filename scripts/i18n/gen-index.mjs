// Writes lib/dict.generated.ts: static imports of every locale's site and
// legal JSON. With --strict (used by `npm run build`), fails unless all 25 exist.
import { existsSync, writeFileSync, readFileSync } from "node:fs";

const src = readFileSync("lib/i18n.ts", "utf8");
const codes = [...src.matchAll(/code: "([a-z-]+)"/g)].map((m) => m[1]);
const strict = process.argv.includes("--strict");
const have = codes.filter((c) => existsSync(`content/site/${c}.json`) && existsSync(`content/legal/${c}.json`));
if (strict && have.length !== codes.length) {
  console.error("missing locales: " + codes.filter((c) => !have.includes(c)).join(", "));
  process.exit(1);
}
const id = (c) => c.replace("-", "_");
const lines = [
  "// Generated by scripts/i18n/gen-index.mjs. Do not edit.",
  ...have.flatMap((c) => [`import site_${id(c)} from "@/content/site/${c}.json";`, `import legal_${id(c)} from "@/content/legal/${c}.json";`]),
  ...codes.filter((c) => existsSync(`scripts/i18n/glossary/${c}.json`)).map((c) => `import gloss_${id(c)} from "@/scripts/i18n/glossary/${c}.json";`),
  "",
  `export const GLOSSARY: Record<string, Record<string, string>> = { ${codes.filter((c) => existsSync(`scripts/i18n/glossary/${c}.json`)).map((c) => `"${c}": gloss_${id(c)}`).join(", ")} };`,
  `export const SITE = { ${have.map((c) => `"${c}": site_${id(c)}`).join(", ")} } as const;`,
  `export const LEGAL = { ${have.map((c) => `"${c}": legal_${id(c)}`).join(", ")} } as const;`,
  "",
];
writeFileSync("lib/dict.generated.ts", lines.join("\n"));
console.log(`dict: ${have.length}/${codes.length} locales`);
